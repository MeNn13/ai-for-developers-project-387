import assert from 'node:assert/strict'
import test from 'node:test'
import { prepare } from './opencode.mjs'
import { publish } from './opencode-publish.mjs'

const issue = {
  number: 12,
  id: 100,
  state: 'open',
  labels: [],
  title: 'Request',
  body: 'Need a change',
  user: { login: 'MeNn13', type: 'User' },
  author_association: 'OWNER',
}
const event = {
  action: 'opened',
  repository: { full_name: 'MeNn13/ai-for-developers-project-387' },
  issue,
}

test('new trusted issue dispatches automatic triage without a command comment', async () => {
  const result = await prepare('issues', event, async (path) =>
    path.includes('/comments') ? [] : issue,
  )
  const context = JSON.parse(result.context)
  assert.equal(context.mode, 'triage')
  assert.equal(context.requestId, 100)
  assert.match(context.request, /triage/)
  assert.deepEqual(context.comments, [])
})

test('triage rejects untrusted, prepared, closed and non-opening events before dispatch', async () => {
  for (const change of [
    { user: { login: 'outsider', type: 'User' } },
    { user: { login: 'MeNn13', type: 'Bot' } },
    { author_association: 'NONE' },
    { state: 'closed' },
    { pull_request: {} },
    ...['ready-for-agent', 'ready-for-human', 'needs-info', 'wontfix'].map((name) => ({
      labels: [{ name }],
    })),
  ]) {
    assert.equal(
      await prepare('issues', { ...event, issue: { ...issue, ...change } }, () =>
        assert.fail('API called'),
      ),
      null,
    )
  }
  assert.equal(
    await prepare('issues', { ...event, action: 'edited' }, () => assert.fail('API called')),
    null,
  )
  assert.equal(
    await prepare('issues', event, async () => ({ ...issue, labels: ['ready-for-agent'] })),
    null,
  )
})

test('automatic publisher only comments once and checks the current issue state', async () => {
  const context = {
    mode: 'triage',
    number: 12,
    requestId: 100,
    repository: event.repository.full_name,
  }
  const comments = []
  let current = issue
  const api = async (method, path, data) => {
    if (method === 'GET' && path === '/issues/12') return current
    if (method === 'GET' && path.includes('/comments?')) return comments
    assert.equal(method, 'POST')
    assert.equal(path, '/issues/12/comments')
    comments.push({ ...data, user: { login: 'github-actions[bot]', type: 'Bot' } })
  }
  await assert.rejects(
    publish(
      {
        version: 1,
        comment: 'Analysis',
        publication: {
          kind: 'spec',
          items: [{ key: 'spec', title: 'Title', body: 'Body', blockedBy: [] }],
        },
      },
      context,
      api,
      'run',
    ),
  )
  assert.equal(comments.length, 0)
  const reply = { version: 1, comment: 'Analysis', publication: null }
  await publish(reply, context, api, 'run')
  await publish(reply, context, api, 'run')
  assert.equal(comments.length, 1)
  assert.match(comments[0].body, /^> \*This was generated by AI during triage\.\*/)
  comments.length = 0
  current = { ...issue, labels: ['ready-for-agent'] }
  await publish(reply, context, api, 'run')
  assert.equal(comments.length, 0)
})
